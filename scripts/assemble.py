#!/usr/bin/env python3
"""Own-source bundle builder, not a native installer or external skill vendor."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
sys.dont_write_bytecode=True
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'common/base/scripts'))
from provider_links import verify
from upstream_artifacts import inspect
import secret_guard as secrets


def inventory(root,product):
    root=Path(root).resolve(strict=True)
    if product not in ('codex','claude'):raise ValueError('unsupported product')
    files={}
    def add(source,target):
        if source.is_symlink() or not source.is_file():raise ValueError('own input is not a regular file')
        if target in files:raise ValueError('output collision')
        data=source.read_bytes()
        if len(data)>2_000_000:raise ValueError('own input limit exceeded')
        files[target]=data
    for name in ('instructions.md','workflow.md'):
        add(root/'common/base'/name,'common/base/'+name)
    for source_base,target_base in ((root/'common/base/skills','common/base/skills'),
        (root/'common/base/references','common/base/references'),
        (root/'common/base/scripts','common/base/scripts'),
        (root/f'adapters/{product}/scripts',f'adapters/{product}/scripts'),
        (root/f'adapters/{product}/skills',f'adapters/{product}/skills'),
        (root/f'adapters/{product}/hooks',f'adapters/{product}/hooks'),
        (root/f'adapters/{product}/mcp',f'adapters/{product}/mcp'),
        (root/'scripts','scripts')):
        for p in sorted(source_base.rglob('*')):
            if p.is_symlink():raise ValueError('symlink in own source inventory')
            if p.is_file():
                if p.name=='bindings.toml' or 'upstream' in p.relative_to(source_base).parts:
                    raise ValueError('old external content/transform input is not allowed')
                if '__pycache__' in p.parts:raise ValueError('generated bytecode is not a source input')
                add(p,str(Path(target_base)/p.relative_to(source_base)))
    name='AGENTS.md' if product=='codex' else 'CLAUDE.md'
    template_path=root/f'adapters/{product}/{name}.template'
    if template_path.is_symlink() or not template_path.is_file():raise ValueError('own template must be a regular file')
    template=template_path.read_text()
    if template.count('{{COMMON_INSTRUCTIONS}}')!=1:raise ValueError('invalid instruction template')
    rendered=template.replace('{{COMMON_INSTRUCTIONS}}',files['common/base/instructions.md'].decode())
    files[name]=rendered.encode()
    native_template=root/f'adapters/{product}/plugin.json.in'
    if native_template.exists():add(native_template,f'adapters/{product}/plugin.json.in')
    for filename in ('LICENSE','NOTICE','SECURITY.md','INSTALL.md'):
        if (root/filename).exists():add(root/filename,filename)
    # Generated root instructions resolve workflow.md beside them. Preserve the
    # canonical source path too, for relative references from own skills.
    files['workflow.md']=files['common/base/workflow.md']
    return files


def output_bytes(output,expected):
    actual={}
    for p in Path(output).rglob('*'):
        if p.is_symlink():raise ValueError('reference in assembled output')
        if p.is_file():
            name=str(p.relative_to(output))
            if name not in expected:raise ValueError('unexpected assembled file')
            if p.stat().st_size>2_000_000:raise ValueError('assembled file limit exceeded')
            actual[name]=p.read_bytes()
    if actual!=expected:raise ValueError('assembled inventory changed')
    return actual


def build(root,product,output,catalog,scope,providers,*,native=None,native_renderer=None):
    root=Path(root).resolve(strict=True);output=Path(output)
    if not output.is_absolute() or output.exists() or output.is_symlink():raise ValueError('new absolute output required')
    output=output.parent.resolve(strict=True)/output.name
    if output==root or root in output.parents:raise ValueError('output must be outside source')
    before=inspect(root,Path(catalog),Path(scope),'assembly')
    if not before['complete'] or before['status']!='pass':raise ValueError('assembly gate did not pass')
    links=verify(root,providers,product)
    files=inventory(root,product)
    if native is not None:
        from package import native_files
        files=(native_renderer or native_files)(root,product,files,native)
    # Ensure the guard declaration covers every own file consumed by this build.
    from upstream_guard import Scope
    declared=Scope(root,Path(scope))
    if output not in declared.artifacts:raise ValueError('output is not declared as the transfer artifact')
    for path in list((root/'common/base').rglob('*'))+list((root/f'adapters/{product}').rglob('*'))+list((root/'scripts').rglob('*')):
        if path.is_file() and not declared.covers(path.resolve()):raise ValueError('source input is outside guard declaration')
    for name in ('LICENSE','NOTICE','SECURITY.md','INSTALL.md'):
        if (root/name).exists() and not declared.covers(root/name):raise ValueError('distribution source is outside guard declaration')
    output.mkdir(mode=0o700)
    # New output only. Partial output is retained on failure, not silently deleted.
    for name,data in files.items():
        target=output/name;target.parent.mkdir(parents=True,exist_ok=True)
        with target.open('xb') as f:f.write(data)
    record={'version':1,'product':product,'native_installable':native is not None,
            'external':[{k:v for k,v in entry.items() if k!='entry'} for entry in links],
            'files':[{'path':name,'sha256':hashlib.sha256(data).hexdigest()} for name,data in files.items()],
            'limits':'Own-source bundle only. Native discovery, trust and installation are not certified.'}
    manifest=json.dumps(record,ensure_ascii=False,indent=2).encode()
    with (output/'assembly.json').open('xb') as f:f.write(manifest)
    # Output must be a declared expanded artifact, not an untracked side directory.
    after=inspect(root,Path(catalog),Path(scope),'transfer')
    if not after['complete'] or after['status']!='pass':raise ValueError('fresh transfer inspection did not pass; output retained for review')
    source_after=inspect(root,Path(catalog),Path(scope),'assembly')
    if source_after.get('fingerprint')!=before.get('fingerprint'):
        raise ValueError('assembly input changed; output retained for review')
    if verify(root,providers,product)!=links:raise ValueError('external declaration changed during build')
    # A manifest is an inventory, not a completion certificate. Failed output stays
    # partial. Check exact actual files before and after scanning, without trusting
    # an older report or a caller's declared inventory.
    expected={**files,'assembly.json':manifest}
    actual=output_bytes(output,expected)
    secrets.scan(list(actual.items()),secrets.trusted_scanner())
    output_bytes(output,expected)

    return record


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--product',choices=['codex','claude'],required=True)
    for arg in ('source-root','output','catalog','scope','providers'):p.add_argument('--'+arg,type=Path,required=True)
    a=p.parse_args()
    try:result=build(a.source_root,a.product,a.output,a.catalog,a.scope,a.providers)
    except Exception:print(json.dumps({'status':'unavailable','message':'assembly incomplete; inspect owned output without overwriting it'}));raise SystemExit(2)
    print(json.dumps({'status':'pass','files':len(result['files']),'native_installable':False}))
