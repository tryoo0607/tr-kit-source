#!/usr/bin/env python3
"""Plan explicit repository enrollment; apply only after reviewing the plan. No global Git changes."""
import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import shlex
import stat
import subprocess
import sys


class InstallError(ValueError):
    pass


def git(repo, *args):
    p = subprocess.run(['git', '-C', str(repo), *args], capture_output=True, text=True, check=True)
    return p.stdout.strip()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def snapshot(path):
    if path.is_symlink():
        raise InstallError('symlink is unsupported: ' + str(path))
    if not path.exists():
        return None
    if not path.is_file():
        raise InstallError('not a regular file: ' + str(path))
    return {'bytes': base64.b64encode(path.read_bytes()).decode(), 'mode': stat.S_IMODE(path.stat().st_mode)}


def same(path, snap):
    return snapshot(path) == snap


def save(path, snap):
    if snap is None:
        if path.exists():
            path.unlink()
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(base64.b64decode(snap['bytes']))
        path.chmod(snap['mode'])


def wrapper(engine, policy, root, original, event):
    # argv remains untouched; pre-push input is buffered once and delivered to both checks and original.
    body = '''#!/usr/bin/env python3
import os, subprocess, sys
from pathlib import Path
payload = sys.stdin.buffer.read() if EVENT == 'pre-push' else None
p = subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True)
if p.returncode:
    sys.exit(2)
enrolled = Path(p.stdout.strip()).resolve() == Path(ROOT)
if enrolled:
    result = subprocess.run([sys.executable, ENGINE, 'push' if EVENT == 'pre-push' else 'index', '--repo', ROOT, '--policy', POLICY], input=payload)
    if result.returncode:
        sys.exit(result.returncode)
if ORIGINAL and os.access(ORIGINAL, os.X_OK):
    result = subprocess.run([ORIGINAL, *sys.argv[1:]], input=payload)
    if result.returncode:
        sys.exit(result.returncode)
    if enrolled and EVENT == 'pre-commit':
        sys.exit(subprocess.run([sys.executable, ENGINE, 'index', '--repo', ROOT, '--policy', POLICY]).returncode)
sys.exit(0)
'''
    values = f'ENGINE = {str(engine)!r}\nPOLICY = {str(policy)!r}\nROOT = {str(root)!r}\nORIGINAL = {str(original) if original else None!r}\nEVENT = {event!r}\n'
    return body.replace('import os, subprocess, sys\n', 'import os, subprocess, sys\n' + values).encode()


def plan(repo, state, scanner, local_only=(), allow_artifacts=()):
    root = Path(git(repo, 'rev-parse', '--show-toplevel')).resolve()
    if allow_artifacts and (root.name != 'tr-local-docs' or any(p.split('/')[-2:] != ['_bmad-output', '**'] or p.startswith('/') or '..' in p.split('/') for p in allow_artifacts)):
        raise InstallError('artifact allowances require a verified tr-local-docs root and explicit _bmad-output/** paths')
    state = Path(state).expanduser().resolve()
    if state.is_relative_to(root):
        raise InstallError('stable runtime must be outside the enrolled worktree')
    if state.exists() and any(state.iterdir()):
        raise InstallError('state directory must be new and empty; use status for an existing enrollment')
    scanner = Path(scanner).expanduser().resolve()
    if not scanner.is_file() or not os.access(scanner, os.X_OK):
        raise InstallError('trusted scanner executable is missing')
    version = subprocess.run([str(scanner), 'version'], capture_output=True, text=True, timeout=10, check=True).stdout.strip()
    if version.lstrip('v') != '8.30.1':
        raise InstallError('Gitleaks must be pinned v8.30.1')
    hooks = Path(git(root, 'rev-parse', '--path-format=absolute', '--git-path', 'hooks')).resolve()
    if state == hooks or state.is_relative_to(hooks):
        raise InstallError('runtime must be outside hooks directory')
    config = subprocess.run(['git', '-C', str(root), 'config', '--show-origin', '--show-scope', '--get-all', 'core.hooksPath'], capture_output=True, text=True)
    files = []
    policy = {'schema_version': 1, 'gitleaks': str(state / 'gitleaks'), 'repositories': [
        {'path': str(root), 'local_only': list(local_only), 'allow_artifacts': list(allow_artifacts)}]}
    for event in ('pre-commit', 'pre-push'):
        target = hooks / event
        before = snapshot(target)
        if before and any(word in base64.b64decode(before['bytes']).lower() for word in (b'husky', b'lefthook', b'generated by pre-commit', b'commit-guard.py')):
            raise InstallError('unsupported or already managed hook: ' + str(target))
        original = hooks / (event + '.tr-kit-original') if before else None
        if original and original.exists():
            raise InstallError('backup path already exists: ' + str(original))
        files.append({'path': str(target), 'before': before,
                      'after': {'bytes': base64.b64encode(wrapper(state / 'commit-guard.py', state / 'policy.json', root, original, event)).decode(), 'mode': 0o755}})
        if original:
            files.append({'path': str(original), 'before': None, 'after': before})
    engine = Path(__file__).with_name('commit-guard.py').read_bytes()
    for name, data, mode in [('commit-guard.py', engine, 0o755), ('gitleaks', scanner.read_bytes(), 0o755),
                             ('policy.json', (json.dumps(policy, indent=2) + '\n').encode(), 0o600)]:
        files.append({'path': str(state / name), 'before': None,
                      'after': {'bytes': base64.b64encode(data).decode(), 'mode': mode}})
    return {'schema_version': 1, 'repository': str(root), 'state': str(state), 'hooks': str(hooks),
            'hooks_config': config.stdout, 'scanner_version': version, 'files': files}


def public(report):
    return {k: v for k, v in report.items() if k != 'files'} | {'files': [
        {'path': item['path'], 'backup': item['before'] is not None,
         'sha256': digest(base64.b64decode(item['after']['bytes']))} for item in report['files']]}


def apply(report):
    config = subprocess.run(['git', '-C', report['repository'], 'config', '--show-origin',
                             '--show-scope', '--get-all', 'core.hooksPath'], capture_output=True, text=True)
    if config.returncode not in (0, 1) or config.stdout != report['hooks_config']:
        raise InstallError('pre-apply conflict: core.hooksPath configuration changed')
    hooks = Path(git(report['repository'], 'rev-parse', '--path-format=absolute', '--git-path', 'hooks')).resolve()
    if str(hooks) != report['hooks']:
        raise InstallError('pre-apply conflict: effective hooks path changed')
    state = Path(report['state'])
    for item in report['files']:
        if not same(Path(item['path']), item['before']):
            raise InstallError('pre-apply conflict: ' + item['path'])
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    state.chmod(0o700)
    written = []
    try:
        # Runtime and originals first, wrappers last. No Git config mutation.
        ordered = sorted(report['files'], key=lambda f: f['path'] in [str(Path(report['hooks']) / n) for n in ('pre-commit', 'pre-push')])
        for item in ordered:
            save(Path(item['path']), item['after'])
            written.append(item)
        receipt = state / 'receipt.json'
        receipt.write_text(json.dumps(report, indent=2) + '\n')
        receipt.chmod(0o600)
    except BaseException:
        for item in reversed(written):
            save(Path(item['path']), item['before'])
        raise
    return public(report)


def status(state, rollback=False):
    receipt = Path(state).resolve() / 'receipt.json'
    report = json.loads(receipt.read_text())
    if report.get('rolled_back'):
        return {'status': 'rolled-back', 'repository': report['repository']}
    conflicts = [f['path'] for f in report['files'] if not same(Path(f['path']), f['after'])]
    config = subprocess.run(['git', '-C', report['repository'], 'config', '--show-origin', '--show-scope', '--get-all', 'core.hooksPath'], capture_output=True, text=True).stdout
    if config != report['hooks_config']:
        conflicts.append('core.hooksPath configuration changed')
    if conflicts:
        if rollback:
            raise InstallError('rollback conflict; no files changed: ' + ', '.join(conflicts))
        return {'status': 'conflict', 'conflicts': conflicts}
    if rollback:
        for item in reversed(report['files']):
            save(Path(item['path']), item['before'])
        report['rolled_back'] = True
        receipt.write_text(json.dumps(report, indent=2) + '\n')
    return {'status': 'rolled-back' if rollback else 'active', 'repository': report['repository']}


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('action', choices=['plan', 'apply', 'status', 'rollback'])
    p.add_argument('--repo', default='.')
    p.add_argument('--state', type=Path, required=True)
    p.add_argument('--gitleaks', type=Path)
    p.add_argument('--local-only', action='append', default=[])
    p.add_argument('--allow-artifact', action='append', default=[])
    a = p.parse_args()
    try:
        if a.action in {'status', 'rollback'}:
            result = status(a.state, a.action == 'rollback')
        else:
            if not a.gitleaks:
                p.error('--gitleaks is required for plan/apply')
            report = plan(a.repo, a.state, a.gitleaks, a.local_only, a.allow_artifact)
            result = apply(report) if a.action == 'apply' else public(report)
        print(json.dumps(result, indent=2))
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        p.exit(2, 'git-guard-install: ' + str(error) + '\n')


if __name__ == '__main__':
    main()
